//! Text measured on a canvas in Inter.
//!
//! Cytoscape (mermaid's architecture layout) measures labels with a canvas
//! `measureText` in `Helvetica Neue, Helvetica, sans-serif`; in mermaid-cli's
//! reference environment fontconfig serves Inter for Helvetica Neue. These are
//! Inter 4.000 Regular's metrics (SIL Open Font License; the advances and
//! HarfBuzz's pair adjustments under its default features), which reproduce
//! headless Chromium's `measureText` widths exactly for text without Inter's
//! contextual punctuation forms (`calt`: `(`, `-`, `:` and the like next to
//! capitals or digits), whose substitutions this table does not model.

/// Width of `text` as a canvas `measureText` reports it in Inter Regular at
/// `font_size`: the shaped advance, unrounded. Characters outside ASCII count by
/// Arial's advance.
pub fn canvas_width(text: &str, font_size: f64) -> f64 {
    let mut units = 0.0f64;
    let mut prev: Option<char> = None;
    for c in text.chars().filter(|&c| !super::mark::is_mark(c)) {
        if let Some(p) = prev {
            units += f64::from(kerning(p, c));
        }
        units += match c as u32 {
            code @ 0x20..=0x7E => f64::from(INTER_ADVANCE[(code - 0x20) as usize]),
            _ => super::arial_char_width_em(c, false) * 2048.0,
        };
        prev = Some(c);
    }
    units / 2048.0 * font_size
}

fn kerning(a: char, b: char) -> i16 {
    if !a.is_ascii() || !b.is_ascii() {
        return 0;
    }
    let key = (a as u8, b as u8);
    INTER_KERNING
        .binary_search_by(|&(x, y, _)| (x, y).cmp(&key))
        .map_or(0, |i| INTER_KERNING[i].2)
}

