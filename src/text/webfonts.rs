//! The web fonts mermaid-cli loads before it renders, and which faces a CSS
//! `font-family` list measures in.
//!
//! mmdc 12.2.0 links `@fontsource-variable/recursive` (the `wght` axis subsets)
//! and `@fontsource/open-sans` 400 / 400 italic into its page and waits for every
//! face to load. mermaid 12.3.0's redux themes (`redux-color` is the default of
//! flowcharts, sequence, class, state, ER, requirement, ...) set
//! `fontFamily: "Recursive Variable", arial, sans-serif`, and the sequence
//! actors, gantt tasks and C4 elements default to `"Open Sans", sans-serif`, so
//! that text is laid out in those fonts. Their metrics ([`super::webfont_data`],
//! generated by `tools/gen_font_tables.py`) reproduce what HarfBuzz (and so
//! Chromium) measures: advances, `kern` pairs and `liga` ligatures under the
//! default features. Recursive's Sans Linear keeps its advances and kerning at
//! every `wght`; Open Sans has no bold face, and Chromium's synthetic bold keeps
//! the regular advances. Characters a face lacks fall back to Arial's metrics,
//! the next family in mermaid's lists.

use super::webfont_data::{OPEN_SANS, OPEN_SANS_ITALIC, RECURSIVE};
use super::webfont_synthetic::{
    OPEN_SANS_BOLD, OPEN_SANS_BOLD_PAIRS, OPEN_SANS_ITALIC_BOLD, OPEN_SANS_ITALIC_LIGATURES,
    OPEN_SANS_LIGATURES, RECURSIVE_SLANT, RECURSIVE_SLANT_BOLD, RECURSIVE_SLANT_POINTS,
};

/// A face's metrics, in font units.
#[derive(Debug)]
pub(crate) struct FaceData {
    pub upem: f64,
    pub ascent: i16,
    /// The descent below the baseline (positive).
    pub descent: i16,
    pub line_gap: i16,
    /// x-height at `wght` 400 and 700 (Recursive's `MVAR` varies it).
    pub x_height: [i16; 2],
    /// Sorted by code point: (code point, advance).
    pub chars: &'static [(u16, u16)],
    /// Per character: `xMin`, `xMax`, `yMin`, `yMax` of its ink, regular and bold.
    pub ink: &'static [(i16, i16, i16, i16)],
    pub ink_bold: &'static [(i16, i16, i16, i16)],
    /// Per character: its left and right kerning class (0: no kerning).
    pub left: &'static [u8],
    pub right: &'static [u8],
    /// Number of right classes (the row length of `kern`).
    pub classes: usize,
    pub kern: &'static [i16],
    /// `liga` substitutions and the ligature's advance.
    pub ligatures: &'static [(&'static str, u16)],
}

impl FaceData {
    fn index(&self, c: char) -> Option<usize> {
        let c = u16::try_from(c as u32).ok()?;
        self.chars.binary_search_by_key(&c, |&(cp, _)| cp).ok()
    }

    /// Whether the face draws `c`.
    pub fn has(&self, c: char) -> bool {
        self.index(c).is_some()
    }

    /// Advance of `c` in em.
    pub fn advance_em(&self, c: char) -> Option<f64> {
        self.index(c)
            .map(|i| f64::from(self.chars[i].1) / self.upem)
    }

    /// Kerning between `a` and `b` in em (0 unless both are in the face).
    pub fn kern_em(&self, a: char, b: char) -> f64 {
        match (self.index(a), self.index(b)) {
            (Some(i), Some(j)) => {
                let k = self.kern
                    [usize::from(self.left[i]) * self.classes + usize::from(self.right[j])];
                f64::from(k) / self.upem
            }
            _ => 0.0,
        }
    }

    /// Ink box of `c` in em: (`xMin`, `xMax`, `yMin`, `yMax`), at the regular or
    /// bold weight (`None` for characters outside the face).
    pub fn ink_em(&self, c: char, bold: bool) -> Option<(f64, f64, f64, f64)> {
        let i = self.index(c)?;
        let (a, b, y0, y1) = if bold { self.ink_bold[i] } else { self.ink[i] };
        let em = |v: i16| f64::from(v) / self.upem;
        Some((em(a), em(b), em(y0), em(y1)))
    }

    /// The ligature `text` starts with, if any (longest first): its length in
    /// characters and its advance in em.
    pub fn ligature_at(&self, text: &[char]) -> Option<(usize, f64)> {
        self.ligatures
            .iter()
            .filter(|(s, _)| {
                let n = s.chars().count();
                text.len() >= n && s.chars().zip(text).all(|(a, &b)| a == b)
            })
            .max_by_key(|(s, _)| s.len())
            .map(|&(s, w)| (s.chars().count(), f64::from(w) / self.upem))
    }
}

/// Open Sans' emboldened ink (see [`Face::synthetic_ink_px`]) from its entry
/// in the bold tables: the first of its pairs, how many bound it on the left
/// and on the right.
fn emboldened_ink_px((at, nl, nh): (u16, u8, u8), size: f64, upem: f64) -> Option<(f64, f64)> {
    let (at, nl, nh) = (usize::from(at), usize::from(nl), usize::from(nh));
    if nl == 0 || nh == 0 {
        return None;
    }
    // `SkScalarInterpFunc(size, {9, 36}, {1/24, 1/32})`, half of it.
    let t = (size.clamp(9.0, 36.0) - 9.0) / 27.0;
    let r = size * (1.0 / 24.0 + t * (1.0 / 32.0 - 1.0 / 24.0)) / 2.0;
    let scale = (size * 64.0).trunc() / upem;
    let at_px =
        |&(x2, a): &(i16, f32)| (f64::from(x2) / 2.0 * scale).round() / 64.0 + r * f64::from(a);
    let low = &OPEN_SANS_BOLD_PAIRS[at..at + nl];
    let high = &OPEN_SANS_BOLD_PAIRS[at + nl..at + nl + nh];
    let lo = low.iter().map(at_px).fold(f64::INFINITY, f64::min);
    let hi = high.iter().map(at_px).fold(f64::NEG_INFINITY, f64::max);
    Some((lo.floor(), hi.ceil()))
}

/// The font a piece of text is measured in.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Hash)]
pub enum Face {
    /// Liberation Sans (metric-compatible Arial), which `"trebuchet ms",
    /// verdana, arial` and `arial` resolve to in mmdc's environment.
    #[default]
    Arial,
    /// Recursive Variable (Sans Linear), the redux themes' font.
    Recursive,
    /// Open Sans 400 (and its italic).
    OpenSans,
    /// The browser's default serif font (Liberation Serif, metric-compatible
    /// with Times New Roman): what a style's `font-family` no installed face
    /// matches falls back to. Its advances and kerning are in [`super::serif`];
    /// bold and italic keep the regular advances, and characters outside ASCII
    /// count by Arial's.
    Serif,
}

impl Face {
    /// The face a node's or a text's own `font-family` (a `style` or `classDef`
    /// declaration) draws in. Names a web font mmdc loads, and the families the
    /// browser resolves to Arial (Liberation Sans) in mmdc's environment, pick
    /// their face; `serif` and the other names of the default serif font pick
    /// [`Face::Serif`]. A list no name of which is known falls back to the
    /// browser's default font, which is serif. `monospace` has no metrics
    /// bundled and measures as Arial.
    pub fn of_style_family(css: &str) -> Face {
        for fam in css.split(',') {
            let name = fam.trim().trim_matches(|c| c == '"' || c == '\'').trim();
            match name.to_ascii_lowercase().as_str() {
                "recursive variable" => return Face::Recursive,
                "open sans" => return Face::OpenSans,
                "serif" | "times new roman" | "times" | "liberation serif" => {
                    return Face::Serif;
                }
                "arial" | "arialmt" | "helvetica" | "liberation sans" | "sans-serif"
                | "trebuchet ms" | "verdana" | "monospace" | "courier" | "courier new" => {
                    return Face::Arial;
                }
                _ => continue,
            }
        }
        Face::Serif
    }

    /// The face a CSS `font-family` list draws Latin text in: its first family
    /// that names a web font mmdc loads, else Arial's metrics (every other list
    /// mermaid uses ends in, or resolves to, Arial in mmdc's environment).
    pub fn of_family(css: &str) -> Face {
        for fam in css.split(',') {
            let name = fam.trim().trim_matches(|c| c == '"' || c == '\'').trim();
            match name.to_ascii_lowercase().as_str() {
                "recursive variable" => return Face::Recursive,
                "open sans" => return Face::OpenSans,
                "" => continue,
                _ => return Face::Arial,
            }
        }
        Face::Arial
    }

    /// The metrics tables of a web font face (`None` for Arial, whose tables
    /// live in [`super`]).
    pub(crate) fn data(self, italic: bool) -> Option<&'static FaceData> {
        match self {
            Face::Arial | Face::Serif => None,
            Face::Recursive => Some(&RECURSIVE),
            Face::OpenSans if italic => Some(&OPEN_SANS_ITALIC),
            Face::OpenSans => Some(&OPEN_SANS),
        }
    }

    /// The CSS family name mmdc's stylesheets give the face.
    pub fn family_name(self) -> &'static str {
        match self {
            Face::Arial => "Arial",
            Face::Serif => "Times New Roman",
            Face::Recursive => "Recursive Variable",
            Face::OpenSans => "Open Sans",
        }
    }

    /// The horizontal ink of `c` in a style Chromium synthesises for a face
    /// that lacks it, as `getBBox()` takes it: `(left, right)` in whole pixels
    /// from the glyph's origin at `size` (the shaping size). `None` where the
    /// face has the style (or the character is not in it).
    ///
    /// * Recursive italic: Blink has Skia skew the glyph by a quarter
    ///   (`setSkewX(-1/4)`) once each outline point is scaled to 26.6 fixed
    ///   point; the control box of the slanted points (`x + y / 4` in floating
    ///   point) is rounded out.
    /// * Open Sans bold: Skia strokes and fills the outline (`kEmbolden`), the
    ///   stroke `size * k` wide, `k` going from 1/24 at 9px to 1/32 at 36px
    ///   (`kStdFakeBoldInterpKeys`), with miter joins; the stroked path's
    ///   control box is rounded out.
    ///
    /// Fitted to the boxes Chromium measures with mmdc's fonts: every one of
    /// 1434 slanted and of 1740 emboldened probes (single glyphs and strings,
    /// 10 to 24px), but one emboldened string whose last glyph's ink ends
    /// 0.0008px short of a pixel by this model.
    pub fn synthetic_ink_px(
        self,
        c: char,
        bold: bool,
        italic: bool,
        size: f64,
    ) -> Option<(f64, f64)> {
        let size26 = (size * 64.0).trunc();
        match self {
            Face::Recursive if italic => {
                let i = RECURSIVE.index(c)?;
                let (at, nl, nh) = if bold {
                    RECURSIVE_SLANT_BOLD[i]
                } else {
                    RECURSIVE_SLANT[i]
                };
                let (at, nl, nh) = (usize::from(at), usize::from(nl), usize::from(nh));
                // (A character without outline counts by its advance.)
                if nl == 0 || nh == 0 {
                    return None;
                }
                let scale = size26 / RECURSIVE.upem;
                let slant = |&(x, y): &(f32, f32)| {
                    (f64::from(x) * scale).round() + (f64::from(y) * scale).round() / 4.0
                };
                let low = &RECURSIVE_SLANT_POINTS[at..at + nl];
                let high = &RECURSIVE_SLANT_POINTS[at + nl..at + nl + nh];
                let lo = low.iter().map(slant).fold(f64::INFINITY, f64::min);
                let hi = high.iter().map(slant).fold(f64::NEG_INFINITY, f64::max);
                Some(((lo / 64.0).floor(), (hi / 64.0).ceil()))
            }
            Face::OpenSans if bold => {
                let d = self.data(italic)?;
                let i = d.index(c)?;
                let entry = if italic {
                    OPEN_SANS_ITALIC_BOLD[i]
                } else {
                    OPEN_SANS_BOLD[i]
                };
                emboldened_ink_px(entry, size, d.upem)
            }
            _ => None,
        }
    }

    /// The ink of the `liga` ligature `text` (one glyph: Open Sans' ff, fi,
    /// fl, ffi, ffl) in whole pixels from its origin at `size`, as
    /// [`Face::synthetic_ink_px`] and Skia's rounding out of the outline's
    /// box (26.6 fixed point) take a glyph's.
    pub fn ligature_ink_px(
        self,
        text: &str,
        bold: bool,
        italic: bool,
        size: f64,
    ) -> Option<(f64, f64)> {
        if self != Face::OpenSans {
            return None;
        }
        let ligs = if italic {
            &OPEN_SANS_ITALIC_LIGATURES
        } else {
            &OPEN_SANS_LIGATURES
        };
        let &(_, lo, hi, at, nl, nh) = ligs.iter().find(|l| l.0 == text)?;
        let upem = self.data(italic)?.upem;
        if bold {
            return emboldened_ink_px((at, nl, nh), size, upem);
        }
        let q = |v: i16| (f64::from(v) / upem * size * 64.0).round() / 64.0;
        Some((q(lo).floor(), q(hi).ceil()))
    }

    /// Vertical metrics in em: ascent, descent, line gap (hhea; the typo metrics
    /// these fonts flag `USE_TYPO_METRICS` for are the same).
    pub fn vertical_em(self) -> (f64, f64, f64) {
        match self.data(false) {
            None => (0.905, 0.212, 67.0 / 2048.0),
            Some(d) => (
                f64::from(d.ascent) / d.upem,
                f64::from(d.descent) / d.upem,
                f64::from(d.line_gap) / d.upem,
            ),
        }
    }

    /// The x-height in em at a weight (bold: `wght` 700).
    pub fn x_height_em(self, bold: bool) -> f64 {
        match self.data(false) {
            None => 1082.0 / 2048.0,
            Some(d) => f64::from(d.x_height[usize::from(bold)]) / d.upem,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn families_resolve_to_the_loaded_web_fonts() {
        assert_eq!(
            Face::of_family("\"Recursive Variable\", arial, sans-serif"),
            Face::Recursive
        );
        assert_eq!(Face::of_family("\"Open Sans\", sans-serif"), Face::OpenSans);
        assert_eq!(Face::of_family("'open sans'"), Face::OpenSans);
        assert_eq!(
            Face::of_family("\"trebuchet ms\", verdana, arial, sans-serif"),
            Face::Arial
        );
        assert_eq!(
            Face::of_family("arial, \"Recursive Variable\""),
            Face::Arial
        );
        assert_eq!(Face::of_family(""), Face::Arial);
    }

    #[test]
    fn tables_hold_harfbuzz_metrics() {
        // Recursive Sans Linear: Latin and Vietnamese, no Cyrillic; `AV` kerns.
        let r = Face::Recursive.data(false).unwrap();
        assert_eq!(r.upem, 1000.0);
        assert!(r.has('a') && r.has('ế') && !r.has('Ж'));
        assert!(r.kern_em('A', 'V') < 0.0);
        assert_eq!(r.kern_em('A', ' '), 0.0);
        // Open Sans: no kerning, five ligatures.
        let o = Face::OpenSans.data(false).unwrap();
        assert_eq!(o.upem, 2048.0);
        assert_eq!(o.kern_em('A', 'V'), 0.0);
        let fi: Vec<char> = "fix".chars().collect();
        assert_eq!(o.ligature_at(&fi), Some((2, 1206.0 / 2048.0)));
        let ffi: Vec<char> = "ffi".chars().collect();
        assert_eq!(o.ligature_at(&ffi).map(|l| l.0), Some(3));
        assert!(Face::OpenSans.data(true).unwrap().advance_em('a') != o.advance_em('a'));
    }
}
